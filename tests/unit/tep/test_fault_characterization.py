"""
M13-B: icab.tep.fault_characterization against the REAL TEP simulator
(fast, short-window runs -- not a mock). These confirm the empirical
mechanism itself works correctly; the actual production catalog
(configs/benchmark/fault_catalog.json) is generated by
scripts/characterize_tep_disturbances.py with a longer window and is not
reproduced exactly here.
"""

from icab.tep.fault_characterization import (
    DisturbanceCharacterization,
    _run_and_sample,
    characterize_disturbance,
)

# Short window for fast unit tests -- long enough for idv_06's strong,
# well-characterized effect (see configs/benchmark/fault_catalog.json)
# to already be visible, not a reproduction of the production window.
_WARMUP = 0.5
_DURATION = 1.5


def test_characterize_disturbance_detects_a_known_strong_effect():
    """idv_06 (A feed loss) is empirically verified with a large,
    multi-measurement effect at the production window (see the fault
    catalog) -- confirm the mechanism detects it even in a short window."""

    result = characterize_disturbance(
        "idv_06", seed=101, warmup_hours=_WARMUP, duration_hours=_DURATION
    )

    assert isinstance(result, DisturbanceCharacterization)
    assert result.icab_injectable is True
    assert result.error is None
    assert "urn:icab:measurement:feed_a_flow" in result.affected_measurements
    assert result.max_deviation_stdevs["urn:icab:measurement:feed_a_flow"] > 4.0


def test_characterize_disturbance_is_deterministic_given_the_same_seed():
    """Same seed/schedule -> bit-identical trajectories (verified
    directly here, not merely asserted) -- so the same characterization
    result, not just a similar one."""

    result_a = characterize_disturbance("idv_06", seed=55, warmup_hours=_WARMUP, duration_hours=_DURATION)
    result_b = characterize_disturbance("idv_06", seed=55, warmup_hours=_WARMUP, duration_hours=_DURATION)

    assert result_a.affected_measurements == result_b.affected_measurements
    assert result_a.max_deviation_stdevs == result_b.max_deviation_stdevs
    assert result_a.plant_tripped == result_b.plant_tripped


def test_run_and_sample_is_bit_identical_across_repeated_calls():
    """The lower-level determinism claim the characterization mechanism
    depends on: identical seed + step/inject sequence -> identical
    sampled measurement trajectory, not merely a similar one."""

    trajectory_a, tripped_a = _run_and_sample(
        seed=7, warmup_hours=_WARMUP, duration_hours=_DURATION,
        sample_interval_hours=0.05, disturbance="idv_01", magnitude=1.0,
    )
    trajectory_b, tripped_b = _run_and_sample(
        seed=7, warmup_hours=_WARMUP, duration_hours=_DURATION,
        sample_interval_hours=0.05, disturbance="idv_01", magnitude=1.0,
    )

    assert trajectory_a.samples == trajectory_b.samples
    assert tripped_a == tripped_b


def test_characterize_disturbance_reports_not_injectable_on_a_bad_name():
    """An unknown disturbance name must be reported as not injectable
    (via TEPSimulator's own validation raising), not silently treated as
    'no effect'."""

    result = characterize_disturbance("idv_not_a_real_one", seed=101, warmup_hours=_WARMUP, duration_hours=_DURATION)

    assert result.icab_injectable is False
    assert result.error is not None
    assert result.affected_measurements == []


def test_characterize_disturbance_reuses_a_supplied_baseline():
    """Passing a precomputed baseline (as characterize_all_disturbances
    does, once per seed) must produce the same result as computing it
    internally -- the reuse is an optimization, not a different
    comparison."""

    baseline, _ = _run_and_sample(
        seed=101, warmup_hours=_WARMUP, duration_hours=_DURATION,
        sample_interval_hours=0.05, disturbance=None, magnitude=0.0,
    )

    with_supplied_baseline = characterize_disturbance(
        "idv_06", seed=101, warmup_hours=_WARMUP, duration_hours=_DURATION, baseline=baseline
    )
    with_internal_baseline = characterize_disturbance(
        "idv_06", seed=101, warmup_hours=_WARMUP, duration_hours=_DURATION
    )

    assert with_supplied_baseline.affected_measurements == with_internal_baseline.affected_measurements
    assert with_supplied_baseline.max_deviation_stdevs == with_internal_baseline.max_deviation_stdevs


def test_a_documented_well_compensated_disturbance_shows_no_measurement_effect_in_this_window():
    """
    idv_04 (reactor cooling water INLET temperature) is a real, known
    case where the closed-loop controller (which manipulates the
    reactor cooling water VALVE specifically to hold reactor_temperature
    at setpoint) compensates the disturbance well enough that no
    MEASUREMENT (as opposed to the uninstrumented valve position) shows
    an above-noise-floor deviation in the production characterization --
    see configs/benchmark/fault_catalog.json and
    docs/architecture/tep-fault-injection.md. This is a genuine empirical
    finding, not a gap in the method: confirm it is still injectable
    (accepted, runs fine) even though no measurement clears the
    threshold.
    """

    result = characterize_disturbance("idv_04", seed=101, warmup_hours=_WARMUP, duration_hours=_DURATION)

    assert result.icab_injectable is True
    assert result.error is None
